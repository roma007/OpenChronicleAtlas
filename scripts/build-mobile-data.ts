import fs from 'node:fs';
import path from 'node:path';

/**
 * 把 data/atlases 生成为移动端可直接 require 的静态映射。
 *
 * 生成物只有 require 语句，不复制数据本身：
 * - 文本数据（.json / .geojson）在 Metro 构建时打包进 App；
 * - 位图封面（.jpg/.png/.webp）作为本地 asset；
 * - .svg 封面暂不打包（React Native Image 不能直接渲染 SVG，界面会走字母占位）。
 *
 * 用法：
 *   pnpm build:mobile-data          # 生成
 *   pnpm build:mobile-data --check  # 校验生成物是否最新
 */

const atlasRoot = path.resolve('data/atlases');
const outDir = path.resolve('apps/mobile/src/generated');
const outFile = path.join(outDir, 'atlasData.ts');

const TEXT_EXT = new Set(['.json', '.geojson']);
const IMAGE_EXT = new Set(['.jpg', '.jpeg', '.png', '.webp']);

function walk(dir: string, base = ''): string[] {
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  const files: string[] = [];
  for (const entry of entries) {
    const relative = base ? `${base}/${entry.name}` : entry.name;
    if (entry.isDirectory()) {
      files.push(...walk(path.join(dir, entry.name), relative));
    } else if (entry.isFile()) {
      files.push(relative);
    }
  }
  return files.sort();
}

function toRequirePath(relative: string): string {
  const absolute = path.join(atlasRoot, relative);
  const required = path.relative(outDir, absolute).split(path.sep).join('/');
  return required.startsWith('.') ? required : `./${required}`;
}

function render(): string {
  const files = walk(atlasRoot);
  const textFiles = files.filter((file) => TEXT_EXT.has(path.extname(file).toLowerCase()));
  const imageFiles = files.filter((file) => IMAGE_EXT.has(path.extname(file).toLowerCase()));

  const lines = [
    '// AUTO-GENERATED by scripts/build-mobile-data.ts — do not edit by hand.',
    '// 重新生成：pnpm build:mobile-data',
    '',
    'export type BundledTextLoader = () => unknown;',
    '',
    'export const BUNDLED_TEXT: Record<string, BundledTextLoader> = {',
    ...textFiles.map(
      (file) => `  ${JSON.stringify(file)}: () => require(${JSON.stringify(toRequirePath(file))}),`,
    ),
    '};',
    '',
    'export const BUNDLED_IMAGES: Record<string, number> = {',
    ...imageFiles.map(
      (file) => `  ${JSON.stringify(file)}: require(${JSON.stringify(toRequirePath(file))}),`,
    ),
    '};',
    '',
  ];
  return `${lines.join('\n')}`;
}

const content = render();

if (process.argv.includes('--check')) {
  const current = fs.existsSync(outFile) ? fs.readFileSync(outFile, 'utf8') : '';
  if (current !== content) {
    console.error('❌ apps/mobile/src/generated/atlasData.ts 已过期，请运行 pnpm build:mobile-data');
    process.exit(1);
  }
  console.log('✅ 移动端内置数据映射已是最新');
} else {
  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(outFile, content);
  const textCount = (content.match(/\(\) => require\(/g) ?? []).length;
  const imageCount = (content.match(/: require\(/g) ?? []).length;
  console.log(
    `✅ 已生成 apps/mobile/src/generated/atlasData.ts（${textCount} 个文本文件 / ${imageCount} 个图片）`,
  );
}
